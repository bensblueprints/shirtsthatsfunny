'use client';

import { motion } from 'motion/react';
import type { ReactNode } from 'react';

/**
 * Scroll reveal. Deliberately restrained: a short rise, once, never replayed.
 * Reduced-motion users get the content with no transform at all.
 */
export default function Reveal({
  children,
  delay = 0,
  className,
}: {
  children: ReactNode;
  delay?: number;
  className?: string;
}) {
  return (
    <motion.div
      className={className}
      initial={{ opacity: 0, y: 22 }}
      whileInView={{ opacity: 1, y: 0 }}
      viewport={{ once: true, margin: '-60px' }}
      transition={{ duration: 0.6, delay, ease: [0.16, 1, 0.3, 1] }}
    >
      {children}
    </motion.div>
  );
}
